/**
 * The preset for a slot's material, or null when Snapmaker ships no generic preset for it. Exact
 * type first ("PETG-CF"), then the family before a suffix ("PLA+" or "PLA Silk" → PLA). An unknown
 * family keeps the reference's values, which is the behaviour before this table existed — a guess at
 * someone else's material is not better than saying nothing.
 */
export function u1FilamentPreset(type: string | undefined): Record<string, string> | null {
  if (!type) return null;
  const t = type.trim().toUpperCase();
  if (U1_FILAMENT_PRESETS[t]) return U1_FILAMENT_PRESETS[t];
  const family = t.match(/^[A-Z]+/)?.[0];
  return family && U1_FILAMENT_PRESETS[family] ? U1_FILAMENT_PRESETS[family] : null;
}

/** Write one slot's material values into a 4-slot config, in place. */
export function applyU1FilamentPreset(cfg: Record<string, unknown>, slot: number, type: string | undefined): void {
  const preset = u1FilamentPreset(type);
  if (!preset) return;
  for (const [k, v] of Object.entries(preset)) {
    const arr = cfg[k];
    if (Array.isArray(arr) && slot < arr.length) arr[slot] = v;
  }
}
